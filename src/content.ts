export const timeSlots: string[] = Array.from({ length: 19 }, (_, index) => {
  const total = 11 * 60 + index * 30
  const hours = Math.floor(total / 60)
  const minutes = total % 60
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}`
})

